"""
HalluciGuard Detector Agent — HaluEval Classifier Edition + Claim-Level Evidence.

Primary detection path: fine-tuned DistilBERT binary classifier trained on the
HaluEval dataset (legacy triage) AND, when an evidence/provenance corpus is
provided, claim-level hybrid evidence verification:

    User Query + LLM Response
         ↓
    Claim decomposition (atomic propositions)
         ↓
    Hybrid evidence retrieval (BM25 + dense + rerank)
         ↓
    DeBERTa NLI claim-evidence label (SUPPORTED / CONTRADICTED / NON-ENOUGH)
         ↓
    Claim-level result + answer-level risk aggregation
         ↓
    Risk classification (LOW/MEDIUM/HIGH)
         │
         ├── LOW / MEDIUM → ACCEPT
         │
         └── HIGH → VERIFIER AGENT

Hallucination probabilities are routing signals, not truth verdicts; only the
evidence-backed Verifier Agent finalizes factual truth.
"""

import logging
from typing import List, Optional

from .config import DetectorConfig
from .halueval_inference import HaluEvalInference
from .models import ClaimRisk, DetectionResult, NextAction, RiskLevel
from .signals.token_surprisal import TokenSurprisalEvaluator

from agents.detector_agent.claims import ClaimType, classify_claim_type

logger = logging.getLogger(__name__)


class DetectorAgent:
    """The Detector Agent estimates the likelihood that an LLM response
    contains hallucinations using a HaluEval-trained classifier.

    Responsibilities:
    - Receive user_query and llm_response.
    - Run inference through the fine-tuned HaluEval DistilBERT model.
    - Produce a hallucination_probability and confidence_score.
    - Classify risk level (LOW, MEDIUM, HIGH).
    - Route: LOW/MEDIUM → Accept, HIGH → Verify (send to Verifier Agent).
    """

    _SHARED_INFERENCE: Optional[HaluEvalInference] = None
    _SHARED_MODEL_LOADED: bool = False

    def __init__(
        self,
        config: Optional[DetectorConfig] = None,
        *,
        evidence_retriever=None,
        nli_classifier=None,
    ) -> None:
        """Initialize DetectorAgent with HaluEval classifier.

        Args:
            config: Optional DetectorConfig. Uses defaults if not provided.
            evidence_retriever: Optional EvidenceRetriever instance for the
                claim-level hybrid evidence path (test seam / caching reuse).
            nli_classifier: Optional ClaimEvidenceClassifier instance for the
                claim-level NLI step (test seam / caching reuse).
        """
        self.config: DetectorConfig = config or DetectorConfig()

        if DetectorAgent._SHARED_INFERENCE is None:
            DetectorAgent._SHARED_INFERENCE = HaluEvalInference(
                model_path=self.config.halueval_model_path,
                max_length=self.config.halueval_max_length,
            )
        self._inference = DetectorAgent._SHARED_INFERENCE
        self._token_evaluator = TokenSurprisalEvaluator()
        self._evidence_retriever = evidence_retriever
        self._nli_classifier = nli_classifier

    def _ensure_model_loaded(self) -> None:
        """Load the HaluEval model if not already loaded."""
        if not DetectorAgent._SHARED_MODEL_LOADED:
            try:
                self._inference.load()
            except Exception as e:
                logger.warning(f"[Detector] Could not load HaluEval model from disk ({e}); using baseline detector.")
            DetectorAgent._SHARED_MODEL_LOADED = True

    def detect(
        self,
        user_query: str,
        llm_response: str,
        *,
        domain: str = "general",
        documents: Optional[List[str]] = None,
    ) -> DetectionResult:
        """Estimate hallucination likelihood for a given query and LLM response.

        Args:
            user_query: The prompt submitted by the user.
            llm_response: The response generated by the LLM.
            domain: Optional domain hint (informational; reserved for future
                domain-weighted retrieval).
            documents: Optional evidence/provenance corpus (document snippets,
                retrieved passages). When provided, the detector performs
                claim-level hybrid evidence verification (retrieval -> rerank ->
                NLI) and labels each claim VERIFIED / CONTRADICTED /
                INSUFFICIENT. When omitted (default), claims are triaged via the
                HaluEval classifier and left UNVERIFIED for the Verifier Agent.

        Returns:
            DetectionResult: Structured output containing confidence_score,
                hallucination_probability, risk_level, and next_action.
        """
        # Validate inputs
        if not user_query or not user_query.strip():
            logger.warning("[Detector] Empty user_query received")
            return self._default_result("Empty query")

        if not llm_response or not llm_response.strip():
            logger.warning("[Detector] Empty llm_response received")
            return self._default_result("Empty response")

        # Load model on first call
        self._ensure_model_loaded()

        # RefChecker-style atomicity: factuality is evaluated per proposition,
        # never by assigning one opaque score to a multi-sentence paragraph.
        # The verifier owns truth; this stage only prioritizes its workload.
        try:
            from agents.verifier_agent.claims.claim_decomposer import ClaimDecomposer

            atomic_claims = ClaimDecomposer().decompose(llm_response)
        except Exception as exc:
            logger.warning("[Detector] Atomic claim extraction degraded: %s", exc)
            atomic_claims = [llm_response.strip()]

        if not atomic_claims:
            atomic_claims = [llm_response.strip()]

        # Evidence-backed claim-level verification when a corpus is supplied;
        # otherwise the legacy HaluEval/surprisal triage path.
        if documents is not None:
            if domain:
                logger.debug("[Detector] evidence mode domain=%s", domain)
            return self._detect_with_evidence(llm_response, atomic_claims, documents)

        return self._detect_legacy(user_query, atomic_claims)

    # ------------------------------------------------------------------
    # Legacy path: HaluEval + surprisal triage (no evidence corpus)
    # ------------------------------------------------------------------
    def _detect_legacy(
        self, user_query: str, atomic_claims: List[str]
    ) -> DetectionResult:
        # Run HaluEval classifier inference for every atomic claim.
        # detector_* diagnostics below guarantee that a failed load can never be
        # mistaken for real ML inference (spec §6).
        model_loaded = bool(getattr(self._inference, "_loaded", False))
        inference_executed = False
        degraded = False
        if model_loaded:
            model_source = str(getattr(self._inference, "model_path", "") or "halueval-distilbert")
        else:
            model_source = "baseline-heuristic"

        claim_results: list[ClaimRisk] = []
        try:
            if model_loaded:
                for index, claim in enumerate(atomic_claims, start=1):
                    claim_type = classify_claim_type(claim)
                    if claim_type == ClaimType.OPINION:
                        # Opinion claims are never factual hallucinations; they
                        # are excluded from factual-risk aggregation (#4).
                        claim_results.append(self._opinion_claim(index, claim, claim_type))
                        continue
                    result = self._inference.predict(user_query, claim)
                    classifier_probability = float(result.hallucination_probability)
                    surprisal_probability = self._token_evaluator.score(
                        user_query, claim
                    )
                    # The supplied fine-tuned checkpoint is empirically
                    # collapsed on contextless production claims.  Prefer the
                    # HalluDetect evaluator signal when it executed; retain the
                    # classifier as an explicit fallback/diagnostic prior.
                    probability = (
                        surprisal_probability
                        if surprisal_probability is not None
                        else classifier_probability
                    )
                    risk = self._determine_risk_level(probability)
                    claim_results.append(
                        ClaimRisk(
                            claim_id=f"c{index}",
                            text=claim,
                            hallucination_probability=round(probability, 4),
                            confidence_score=round(1.0 - probability, 4),
                            risk_level=risk,
                            requires_verification=risk != RiskLevel.LOW,
                            classifier_probability=round(classifier_probability, 4),
                            token_surprisal_probability=(
                                round(surprisal_probability, 4)
                                if surprisal_probability is not None
                                else None
                            ),
                            claim_type=claim_type.value,
                            verification_status="UNVERIFIED",
                        )
                    )
                # A response is only as safe as its riskiest factual claim;
                # opinion claims (carrier 0.0) never raise this maximum.
                factual_claims = [
                    item for item in claim_results
                    if item.claim_type != ClaimType.OPINION.value
                ]
                hallucination_prob = max(
                    item.hallucination_probability for item in factual_claims
                ) if factual_claims else 0.0
                confidence_score = min(
                    item.confidence_score for item in factual_claims
                ) if factual_claims else 1.0
                inference_executed = True
            else:
                # Detector NOT proven — degraded. Emit an HONEST "unknown" posture
                # (0.5) rather than a fabricated confident-low 0.08/0.92, which
                # masqueraded a dead model as a safe answer. 0.5 maps to HIGH ->
                # VERIFY, so a degraded detector always routes to evidence.
                degraded = True
                claim_results = []
                for index, claim in enumerate(atomic_claims, start=1):
                    claim_type = classify_claim_type(claim)
                    if claim_type == ClaimType.OPINION:
                        claim_results.append(self._opinion_claim(index, claim, claim_type))
                        continue
                    claim_results.append(
                        ClaimRisk(
                            claim_id=f"c{index}",
                            text=claim,
                            hallucination_probability=0.5,
                            confidence_score=0.5,
                            risk_level=self._determine_risk_level(0.5),
                            # A degraded detector can never authorize a fast path.
                            requires_verification=True,
                            claim_type=claim_type.value,
                            verification_status="UNVERIFIED",
                        )
                    )
                factual_claims = [
                    item for item in claim_results
                    if item.claim_type != ClaimType.OPINION.value
                ]
                if factual_claims:
                    hallucination_prob = 0.5
                    confidence_score = 0.5
                else:
                    # Entirely opinion content is not a hallucination, even with
                    # a degraded factual detector.
                    hallucination_prob = 0.0
                    confidence_score = 1.0
        except Exception as e:
            logger.error(f"[Detector] Inference failed: {e}")
            return self._default_result(f"Inference error: {e}")

        # Determine risk level and next action
        risk_level = self._determine_risk_level(hallucination_prob)
        next_action = self._determine_next_action(risk_level)
        unverified_count = sum(
            1 for item in claim_results
            if item.claim_type != ClaimType.OPINION.value
        )
        opinion_count = len(claim_results) - unverified_count

        logger.info(
            f"[Detector] hallucination_probability={hallucination_prob:.4f} "
            f"risk_level={risk_level.value} next_action={next_action.value} "
            f"model_loaded={model_loaded} inference_executed={inference_executed} "
            f"degraded={degraded}"
        )

        return DetectionResult(
            confidence_score=round(confidence_score, 4),
            hallucination_probability=round(hallucination_prob, 4),
            risk_level=risk_level,
            next_action=next_action,
            model_source=model_source,
            status="degraded" if degraded else "completed",
            detector_model_loaded=model_loaded,
            detector_inference_executed=inference_executed,
            detector_degraded=degraded,
            detector_model_source=model_source,
            atomic_claims=atomic_claims,
            per_claim_results=claim_results,
            evaluator_inference_executed=any(
                item.token_surprisal_probability is not None for item in claim_results
            ),
            evaluator_model_source=self._token_evaluator.model_name,
            claim_count=len(claim_results),
            unverified_count=unverified_count,
            opinion_count=opinion_count,
            requires_verification=next_action == NextAction.VERIFY,
            verification_risk=round(hallucination_prob, 4),
            nli_engine_loaded=False,
            nli_inference_executed=False,
            nli_degraded=False,
        )

    # ------------------------------------------------------------------
    # Evidence path: claim-level hybrid retrieval + NLI verification
    # ------------------------------------------------------------------
    def _detect_with_evidence(
        self,
        llm_response: str,
        atomic_claims: List[str],
        documents: List[str],
    ) -> DetectionResult:
        from agents.detector_agent.evidence import EvidenceRetriever
        from agents.detector_agent.nli import (
            CONTRADICTED,
            NOT_ENOUGH_INFO,
            SUPPORTED,
            ClaimEvidenceClassifier,
        )

        retriever = self._evidence_retriever or EvidenceRetriever()
        classifier = self._nli_classifier or ClaimEvidenceClassifier()

        claim_results: list[ClaimRisk] = []
        supported_count = 0
        contradicted_count = 0
        unknown_count = 0
        unverified_count = 0
        opinion_count = 0
        nli_inference_executed = False
        nli_degraded = False
        evidence_hit_any = False

        for index, claim in enumerate(atomic_claims, start=1):
            claim_type = classify_claim_type(claim)
            if claim_type == ClaimType.OPINION:
                opinion_count += 1
                claim_results.append(self._opinion_claim(index, claim, claim_type))
                continue

            evidence = retriever.retrieve_evidence(claim, documents)
            if not evidence.retrieved or not evidence.items:
                # No relevant evidence for this claim -> UNVERIFIED, never a
                # hands-free verdict (task: "if none, that claim is marked
                # UNVERIFIED with requires_verification=True").
                unverified_count += 1
                claim_results.append(self._unverified_claim(index, claim, claim_type))
                nli_degraded = True
                continue

            evidence_hit_any = True
            best = evidence.items[0]
            outcome = classifier.classify(claim, best.text)
            nli_degraded = nli_degraded or outcome.degraded
            if not outcome.degraded:
                nli_inference_executed = True

            if outcome.label == SUPPORTED:
                supported_count += 1
                verification_status = "VERIFIED"
                # Fail-closed: only a real DeBERTa NLI run may authorize the
                # fast path. Deterministic-fallback support still routes to the
                # Verifier Agent because its weights are non-calibrated.
                requires_verification = outcome.degraded
                carrier = 0.0 if not outcome.degraded else 0.5
            elif outcome.label == CONTRADICTED:
                contradicted_count += 1
                verification_status = "CONTRADICTED"
                requires_verification = True
                carrier = max(0.5, float(outcome.contradicted_probability))
            else:  # NOT_ENOUGH_INFO — never treated as contradictio
                unknown_count += 1
                verification_status = "INSUFFICIENT"
                requires_verification = True
                carrier = 0.5

            claim_results.append(
                ClaimRisk(
                    claim_id=f"c{index}",
                    text=claim,
                    hallucination_probability=round(float(carrier), 4),
                    confidence_score=round(1.0 - float(carrier), 4),
                    risk_level=(
                        RiskLevel.HIGH if requires_verification else RiskLevel.LOW
                    ),
                    requires_verification=requires_verification,
                    claim_type=claim_type.value,
                    verification_status=verification_status,
                    supported_probability=outcome.supported_probability,
                    contradicted_probability=outcome.contradicted_probability,
                    unknown_probability=outcome.unknown_probability,
                    evidence_snippets=[best.text],
                    retrieval_method=best.retrieval_method,
                    nli_degraded=outcome.degraded,
                )
            )

        factual_claims = [
            item for item in claim_results
            if item.claim_type != ClaimType.OPINION.value
        ]
        if factual_claims:
            hallucination_prob = max(
                item.hallucination_probability for item in factual_claims
            )
            confidence_score = min(item.confidence_score for item in factual_claims)
        else:
            hallucination_prob = 0.0
            confidence_score = 1.0

        risk_level = self._determine_risk_level(hallucination_prob)
        next_action = self._determine_next_action(risk_level)

        model_source = (
            "claim-level-hybrid-evidence:deberta-nli"
            if nli_inference_executed
            else "claim-level-hybrid-evidence:deterministic-fallback"
        )
        degraded_status = not nli_inference_executed

        logger.info(
            f"[Detector] evidence hallucination_probability={hallucination_prob:.4f} "
            f"risk_level={risk_level.value} next_action={next_action.value} "
            f"supported={supported_count} contradicted={contradicted_count} "
            f"insufficient={unknown_count} unverified={unverified_count} "
            f"opinion={opinion_count} nli_inference_executed={nli_inference_executed} "
            f"evidence_hits={evidence_hit_any}"
        )

        return DetectionResult(
            confidence_score=round(confidence_score, 4),
            hallucination_probability=round(hallucination_prob, 4),
            risk_level=risk_level,
            next_action=next_action,
            model_source=model_source,
            status="degraded" if degraded_status else "completed",
            detector_model_loaded=bool(getattr(self._inference, "_loaded", False)),
            detector_inference_executed=False,
            detector_degraded=degraded_status,
            detector_model_source=model_source,
            atomic_claims=atomic_claims,
            per_claim_results=claim_results,
            evaluator_inference_executed=False,
            evaluator_model_source="",
            claim_count=len(claim_results),
            supported_count=supported_count,
            contradicted_count=contradicted_count,
            unknown_count=unknown_count,
            unverified_count=unverified_count,
            opinion_count=opinion_count,
            requires_verification=next_action == NextAction.VERIFY,
            evidence_available=True,
            verification_risk=round(hallucination_prob, 4),
            nli_engine_loaded=nli_inference_executed,
            nli_inference_executed=nli_inference_executed,
            nli_degraded=nli_degraded,
        )

    # ------------------------------------------------------------------
    # Per-claim helpers
    # ------------------------------------------------------------------
    def _opinion_claim(self, index: int, claim: str, claim_type) -> ClaimRisk:
        """Opinion claims carry no factual hallucination risk and are skipped."""
        return ClaimRisk(
            claim_id=f"c{index}",
            text=claim,
            hallucination_probability=0.0,
            confidence_score=1.0,
            risk_level=RiskLevel.LOW,
            requires_verification=False,
            claim_type=claim_type.value,
            verification_status="SKIPPED",
        )

    def _unverified_claim(self, index: int, claim: str, claim_type) -> ClaimRisk:
        """A claim without evidence is UNVERIFIED and must route to the verifier."""
        return ClaimRisk(
            claim_id=f"c{index}",
            text=claim,
            hallucination_probability=0.5,
            confidence_score=0.5,
            risk_level=RiskLevel.HIGH,
            requires_verification=True,
            claim_type=claim_type.value,
            verification_status="UNVERIFIED",
        )

    def _determine_risk_level(self, hallucination_prob: float) -> RiskLevel:
        """Map hallucination probability to a RiskLevel based on configured thresholds.
        
        LOW:    hallucination_probability <= low_risk_threshold (default 0.30)
        MEDIUM: low_risk_threshold < hallucination_probability < high_risk_threshold
        HIGH:   hallucination_probability >= high_risk_threshold (default 0.50)
        """
        if hallucination_prob <= self.config.low_risk_threshold:
            return RiskLevel.LOW
        elif hallucination_prob >= self.config.high_risk_threshold:
            return RiskLevel.HIGH
        return RiskLevel.MEDIUM

    def _determine_next_action(self, risk_level: RiskLevel) -> NextAction:
        """Determine next pipeline action based on risk level.

        Critical routing requirement:
            LOW    → ACCEPT (no verification needed)
            MEDIUM → ACCEPT (no verification needed)
            HIGH   → VERIFY (send to Verifier Agent)
        """
        if risk_level == RiskLevel.HIGH:
            return NextAction.VERIFY
        return NextAction.ACCEPT

    def _default_result(self, reason: str) -> DetectionResult:
        """Return a safe default result for error/edge cases.

        Defaults to HIGH-risk verification. Detector failure must fail closed;
        it must never authorize an unverified response. Previously this returned
        MEDIUM/ACCEPT, which silently PASSED an unverified answer on empty input
        or an inference error — directly contradicting this docstring and the
        fail-closed design. It now emits HIGH/VERIFY with status='degraded'.
        """
        logger.warning(f"[Detector] Using default result: {reason}")
        return DetectionResult(
            confidence_score=0.50,
            hallucination_probability=0.50,
            risk_level=RiskLevel.HIGH,
            next_action=NextAction.VERIFY,
            model_source="baseline-heuristic",
            status="degraded",
            detector_model_loaded=bool(getattr(self._inference, "_loaded", False)),
            detector_inference_executed=False,
            detector_degraded=True,
            detector_model_source=f"default:{reason}",
            atomic_claims=[],
            per_claim_results=[],
        )

